from pathlib import Path
import pandas as pd
import streamlit as st
import plotly.express as px

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"

st.set_page_config(page_title="Amazon Electronics Analytics", page_icon="📊", layout="wide")
st.title("Amazon Electronics | Product & Review Analytics")
st.caption(
    "Historical product-review analytics (1999–2018). Review activity is not sales, "
    "revenue, conversion, or market share."
)

@st.cache_data
def load(name):
    path = OUT / name
    if not path.exists():
        st.error(f"Missing output file: {path.name}. Run the analysis pipeline first.")
        st.stop()
    return pd.read_csv(path)

k = load("kpis.csv").iloc[0]
monthly = load("monthly_trends.csv")
category = load("category_performance.csv")
brand = load("brand_performance.csv")
product = load("product_performance.csv")
segments = load("reviewer_segments_summary.csv")
rating = load("rating_distribution.csv")

# New pipeline versions include category-level tables so filtering is consistent.
monthly_cat_path = OUT / "monthly_trends_by_category.csv"
rating_cat_path = OUT / "rating_distribution_by_category.csv"
segments_cat_path = OUT / "reviewer_segments_by_category.csv"
monthly_cat = load("monthly_trends_by_category.csv") if monthly_cat_path.exists() else None
rating_cat = load("rating_distribution_by_category.csv") if rating_cat_path.exists() else None
segments_cat = load("reviewer_segments_by_category.csv") if segments_cat_path.exists() else None

with st.sidebar:
    st.header("Explore the data")
    cats = sorted(category["category"].dropna().unique().tolist())
    selected = st.multiselect("Category", cats, default=cats)
    min_reviews = st.slider("Minimum reviews per product", 1, 500, 50, 5)
    st.caption("Choose categories to filter the analysis. Select all categories for the full dataset.")

selected_set = set(selected)
fcat = category[category["category"].isin(selected_set)].copy()
fprod = product[product["category"].isin(selected_set) & (product["review_count"] >= min_reviews)].copy()
fbrand = brand.copy()

# Global dataset KPIs are deliberately labelled as global, so filters do not mislead.
st.subheader("Dataset-wide overview")
c1, c2, c3, c4, c5 = st.columns(5)
c1.metric("Review records", f"{int(k.review_records):,}")
c2.metric("Products", f"{int(k.unique_products):,}")
c3.metric("Reviewers", f"{int(k.unique_reviewers):,}")
c4.metric("Average rating", f"{float(k.average_rating):.2f}/5")
c5.metric("Low ratings (1–2)", f"{float(k.low_rating_share_pct):.1f}%")
st.caption("The KPI cards above describe the complete dataset and are not affected by the category filter.")

if not selected:
    st.info("Select at least one category in the sidebar to explore filtered charts and tables.")
    st.stop()

# Filtered time series when generated by the updated pipeline; gracefully support older outputs.
st.subheader("Review activity over time")
if monthly_cat is not None:
    fm = monthly_cat[monthly_cat["category"].isin(selected_set)]
    monthly_view = fm.groupby("review_month", as_index=False).agg(
        review_count=("review_count", "sum"),
        average_rating=("average_rating", "mean"),
        low_rating_share=("low_rating_share", "mean"),
    )
else:
    monthly_view = monthly.copy()
    st.caption("Run the updated pipeline to enable category-filtered monthly trends; this chart currently shows all categories.")
monthly_view = monthly_view.sort_values("review_month")
fig = px.line(
    monthly_view, x="review_month", y="review_count", markers=False,
    labels={"review_month": "Month", "review_count": "Review records"},
    title="Monthly review volume"
)
fig.update_layout(xaxis=dict(type="category", nticks=10), margin=dict(t=55, l=20, r=20, b=20))
st.plotly_chart(fig, use_container_width=True)

left, right = st.columns(2)
with left:
    st.subheader("Category volume vs satisfaction")
    fig = px.scatter(
        fcat, x="review_count", y="average_rating", size="unique_products",
        color="category", hover_data={"low_rating_share": ":.1f", "review_share_pct": ":.1f"},
        labels={"review_count": "Review records", "average_rating": "Average rating",
                "unique_products": "Unique products", "low_rating_share": "Low-rating share (%)",
                "review_share_pct": "Share of review records (%)"}
    )
    fig.update_layout(margin=dict(t=20, l=10, r=10, b=20))
    st.plotly_chart(fig, use_container_width=True)

with right:
    st.subheader("Rating distribution")
    if rating_cat is not None:
        fr = rating_cat[rating_cat["category"].isin(selected_set)].groupby(
            "rating", as_index=False
        ).agg(review_count=("review_count", "sum"))
        total = fr["review_count"].sum()
        fr["review_share_pct"] = (fr["review_count"] / total * 100).round(2) if total else 0
    else:
        fr = rating.copy()
        st.caption("Showing full-dataset distribution until the updated pipeline is run.")
    fig = px.bar(
        fr, x="rating", y="review_share_pct", text=fr["review_share_pct"].map(lambda x: f"{x:.1f}%"),
        labels={"rating": "Rating (1–5)", "review_share_pct": "Share of review records (%)"},
        title="Share of records by rating"
    )
    fig.update_xaxes(dtick=1)
    fig.update_yaxes(ticksuffix="%")
    fig.update_layout(margin=dict(t=45, l=20, r=20, b=20))
    st.plotly_chart(fig, use_container_width=True)

st.subheader("Category scorecard")
score_cols = [c for c in [
    "category", "review_count", "average_rating", "unique_products", "unique_reviewers",
    "low_rating_share", "positive_rating_share", "review_share_pct"
] if c in fcat.columns]
score = fcat[score_cols].sort_values("review_count", ascending=False).copy()
for c in ["low_rating_share", "positive_rating_share", "review_share_pct"]:
    if c in score.columns:
        score[c] = score[c].map(lambda x: f"{x:.1f}%")
st.dataframe(score, use_container_width=True, hide_index=True)

left, right = st.columns(2)
with left:
    st.subheader("Brands by review activity")
    # Brand performance is not category-sliced in the old schema. Avoid pretending it is.
    if "category" in brand.columns:
        b = brand[brand["category"].isin(selected_set)]
    else:
        b = brand.copy()
        st.caption("Brand chart is dataset-wide; brand summaries are not split by category.")
    b = b[b["brand"] != "Unknown brand"].sort_values("review_count", ascending=False).head(15)
    if not b.empty:
        fig = px.bar(
            b.sort_values("review_count"), x="review_count", y="brand", orientation="h",
            color="average_rating", hover_data=["unique_products", "low_rating_share"],
            labels={"review_count": "Review records", "brand": "Brand",
                    "average_rating": "Average rating", "low_rating_share": "Low-rating share (%)"}
        )
        st.plotly_chart(fig, use_container_width=True)
    else:
        st.info("No labelled brands are available for this selection.")

with right:
    st.subheader("Reviewer activity segments")
    if segments_cat is not None:
        fs = segments_cat[segments_cat["category"].isin(selected_set)].groupby(
            "reviewer_segment", as_index=False
        ).agg(reviewers=("reviewers", "sum"))
        fs["reviewer_share_pct"] = fs["reviewers"] / fs["reviewers"].sum() * 100
    else:
        fs = segments.copy()
        st.caption("Reviewer segments are dataset-wide until the updated pipeline is run.")
        if "reviewer_share_pct" not in fs.columns:
            fs["reviewer_share_pct"] = fs["reviewers"] / fs["reviewers"].sum() * 100
    fig = px.bar(
        fs, x="reviewer_segment", y="reviewer_share_pct", text=fs["reviewer_share_pct"].map(lambda x: f"{x:.1f}%"),
        labels={"reviewer_segment": "Reviewer segment", "reviewer_share_pct": "Share of reviewers (%)"},
        title="Reviewer distribution by segment"
    )
    fig.update_yaxes(ticksuffix="%")
    fig.update_layout(xaxis_tickangle=-15, margin=dict(t=45, l=20, r=20, b=20))
    st.plotly_chart(fig, use_container_width=True)

st.subheader("Product-level investigation")
st.caption(
    "Products below the selected review threshold are excluded to reduce small-sample noise. "
    "Review count measures review activity, not sales volume."
)
product_cols = [c for c in [
    "item_id", "category", "brand", "review_count", "average_rating",
    "low_rating_share", "positive_rating_share", "unique_reviewers", "first_review", "last_review"
] if c in fprod.columns]
st.dataframe(
    fprod.sort_values(["review_count", "average_rating"], ascending=[False, False])[product_cols].head(200),
    use_container_width=True, hide_index=True
)

with st.expander("Data quality and interpretation notes"):
    st.markdown("""
    - This dataset contains product review/rating records, not orders, units sold, prices, or revenue.
    - Review count is a measure of observed review activity; it is not sales share or market share.
    - The data is historical (1999–2018) and should not be used to describe today's marketplace.
    - Missing brand labels are retained as `Unknown brand`; brand comparisons are limited by this missingness.
    - Reviewer segments describe how often an ID appears in this dataset, not verified customer retention.
    - These are descriptive observational patterns and do not establish causal drivers of satisfaction.
    """)
